def row(d):
    def v(x):
        if isinstance(x, bool):
            return "true" if x else "false"
        if isinstance(x, (int, float)):
            return str(x)
        if x == "" or x[0] in "0123456789-+" or ":" in x:
            return f"'{x}'"
        return x
    return "  - {" + ", ".join(f"{k}: {v(x)}" for k, x in d.items()) + "}"


